// 게임 격자 시간 g(초, 곡 bpm 기준) ↔ 곡 파일 위치 p(초). game.js·editor.html 공용
//   tempo 있으면 마디 기준점 사이를 선형으로, 없으면 고정 BPM + offset
function tempoSeg(A, key, v) {
  let i = 0;
  while (i < A.length - 2 && A[i + 1][key] <= v) i++;
  return [A[i], A[i + 1]];
}
function songFileAt(song, g) {
  if (!song.tempo) return g + song.offset;
  const bar = g / (240 / song.bpm), [[b0, t0], [b1, t1]] = tempoSeg(song.tempo, 0, bar);
  return t0 + (bar - b0) / (b1 - b0) * (t1 - t0);
}
function songGridAt(song, p) {
  if (!song.tempo) return p - song.offset;
  const [[b0, t0], [b1, t1]] = tempoSeg(song.tempo, 1, p);
  return (b0 + (p - t0) / (t1 - t0) * (b1 - b0)) * (240 / song.bpm);
}

